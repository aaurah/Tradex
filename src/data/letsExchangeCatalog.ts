// Generate dynamic 22M+ market matrix expandable pool
export function buildLetsExchange22MMarketsCatalog(): Coin[] {
  const combinedMap = new Map<string, Coin>();

  // 1. Seed with curated TOP_LETSEXCHANGE_COINS
  TOP_LETSEXCHANGE_COINS.forEach((coin, idx) => {
    const key = `${coin.symbol.toUpperCase()}_${(coin.networkCode || 'default').toUpperCase()}`;
    combinedMap.set(key, { ...coin, rank: idx + 1 });
  });

  // 2. Merge with comprehensive 2,200+ LetsExchange coins universe
  const fullUniverse = generateFullLetsExchangeUniverse();
  fullUniverse.forEach((coin) => {
    const key = `${coin.symbol.toUpperCase()}_${(coin.networkCode || 'default').toUpperCase()}`;
    if (!combinedMap.has(key)) {
      combinedMap.set(key, {
        ...coin,
        rank: combinedMap.size + 1
      });
    }
  });

  return Array.from(combinedMap.values());
}

